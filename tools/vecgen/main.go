var descriptions = []string{"pix", "Pix to Bob", "Card capture", "Devolu\u00e7\u00e3o", "\u20ac transfer", "\U0001F642", "", "MED block", "almo\u00e7o"}
var metaKeys = []string{"end_to_end_id", "a", "b", "Zeta", "a\u00e7\u00e3o", "\u20ac", "\U0001F642", "nsu"}
var metaValues = []string{"", "1", "S\u00e3o Paulo", "E1234567820261102090000000000001", "\U0001F642\U0001F642", "x y z"}

func randMeta() []string {
	n := rng.Intn(4)
	used := map[string]bool{}
	var out []string
	for i := 0; i < n; i++ {
		k := metaKeys[rng.Intn(len(metaKeys))]
		if used[k] {
			continue
		}
		used[k] = true
		out = append(out, k, metaValues[rng.Intn(len(metaValues))])
	}
	return out
}

// randomScenario runs seeded random traffic: transfers with fees, holds
// with timeouts, partial captures, voids, expiry sweeps, reversals,
// replays, conflicting retries, freezes and malformed requests.
func randomScenario(s *scenario) {
	const wallets = 6
	wallet := func(i int) ledger.AccountID { return ledger.AccountID(fmt.Sprintf("wallet:%02d", i)) }
	for _, a := range []ledger.Account{
		{ID: "asset:settlement", Code: "1.1.01", Currency: money.BRL, Type: ledger.Asset},
		{ID: "revenue:fees", Code: "3.1.01", Currency: money.BRL, Type: ledger.Revenue},
		{ID: "payable:partner", Code: "2.2.01", Currency: money.BRL, Type: ledger.Liability},
		{ID: "usd:cash", Code: "1.2.01", Currency: money.USD, Type: ledger.Asset},
		{ID: "usd:wallet", Code: "2.3.01", Currency: money.USD, Type: ledger.Liability, Flags: ledger.NoOverdraft},
	} {
		s.open(a)
	}
	for i := 0; i < wallets; i++ {
		s.open(ledger.Account{ID: wallet(i), Code: fmt.Sprintf("2.1.%02d", i), Name: fmt.Sprintf("Wallet %d", i),
			Currency: money.BRL, Type: ledger.Liability, Flags: ledger.NoOverdraft})
	}
	for i := 0; i < wallets; i++ {
		s.run(&op{Op: "post", Key: fmt.Sprintf("fund-%d", i), Desc: "funding",
			Postings: ps(dr("asset:settlement", brl(500_00)), cr(wallet(i), brl(500_00)))})
	}
	s.run(&op{Op: "post", Key: "fund-usd", Postings: ps(dr("usd:cash", money.New(100_00, money.USD)), cr("usd:wallet", money.New(100_00, money.USD)))})

	type holdRec struct {
		id    ledger.TxID
		total int64
	}
	var posted []*op
	var postedIDs, allIDs []ledger.TxID
	var holds []holdRec
	var frozen []ledger.AccountID
	nkey := 0
	key := func() string {
		if rng.Intn(5) == 0 {
			return ""
		}
		nkey++
		return fmt.Sprintf("k-%d", nkey)
	}
	pair := func() (ledger.AccountID, ledger.AccountID) {
		a := rng.Intn(wallets)
		b := (a + 1 + rng.Intn(wallets-1)) % wallets
		return wallet(a), wallet(b)
	}
	advance := func() int64 {
		if rng.Intn(3) == 0 {
			return int64(rng.Intn(45))
		}
		return 0
	}
	track := func(id ledger.TxID) {
		if id != "" {
			allIDs = append(allIDs, id)
		}
	}
	anyID := func() ledger.TxID {
		if len(allIDs) == 0 || rng.Intn(10) == 0 {
			return ledger.TxID(fmt.Sprintf("tx-%03d", 900+rng.Intn(50)))
		}
		return allIDs[rng.Intn(len(allIDs))]
	}

	for i := 0; i < 320; i++ {
		switch p := rng.Intn(100); {
		case p < 28: // transfer with a fee split 70/30
			from, to := pair()
			amt := brl(1 + rng.Int63n(300_00))
			fee := brl(amt.Minor()/100 + 1)
			split, _ := fee.Allocate(70, 30)
			total, _ := amt.Add(fee)
			legs := ps(dr(from, total), cr(to, amt), cr("revenue:fees", split[0]))
			if split[1].IsPositive() {
				legs = append(legs, cr("payable:partner", split[1]))
			}
			o := &op{Op: "post", Advance: advance(), Key: key(), Desc: descriptions[rng.Intn(len(descriptions))], Meta: randMeta(), Postings: legs}
			id := s.run(o)
			track(id)
			if id != "" {
				posted = append(posted, o)
				postedIDs = append(postedIDs, id)
			}
		case p < 40: // hold, sometimes with a fee leg
			from, to := pair()
			amt := 1 + rng.Int63n(250_00)
			legs := ps(dr(from, brl(amt)), cr(to, brl(amt)))
			if rng.Intn(3) == 0 {
				fee := 1 + amt/50
				legs = ps(dr(from, brl(amt+fee)), cr(to, brl(amt)), cr("revenue:fees", brl(fee)))
				amt += fee
			}
			timeout := []int64{0, 0, 30, 60, 120, 600}[rng.Intn(6)]
			id := s.run(&op{Op: "hold", Advance: advance(), Key: key(), Desc: descriptions[rng.Intn(len(descriptions))], Meta: randMeta(),
				Timeout: timeout, Postings: legs})
			track(id)
			if id != "" {
				holds = append(holds, holdRec{id, amt})
			}
		case p < 54: // resolve a hold (or something that is not one)
			o := &op{Op: "post_pending", Advance: advance(), Key: key(), Desc: descriptions[rng.Intn(len(descriptions))], Meta: randMeta()}
			var total int64 = 100
			if len(holds) > 0 && rng.Intn(8) != 0 {
				k := rng.Intn(len(holds))
				o.Ref, total = holds[k].id, holds[k].total
				if rng.Intn(4) != 0 {
					holds = append(holds[:k], holds[k+1:]...)
				}
			} else {
				o.Ref = anyID()
			}
			switch rng.Intn(4) {
			case 0:
				o.Op = "void_pending"
			case 1:
			default:
				o.AmountCur = money.BRL
				o.Amount = rng.Int63n(total + 3)
				if rng.Intn(15) == 0 {
					o.AmountCur = money.USD
				}
			}
			track(s.run(o))
		case p < 63: // reversal
			o := &op{Op: "reverse", Advance: advance(), Key: key(), Desc: "refund"}
			if len(postedIDs) > 0 && rng.Intn(4) != 0 {
				o.Ref = postedIDs[rng.Intn(len(postedIDs))]
			} else {
				o.Ref = anyID()
			}
			if rng.Intn(20) == 0 {
				o.AmountCur, o.Amount = money.BRL, 1
			}
			track(s.run(o))
		case p < 71 && len(posted) > 0: // exact retry: must replay
			orig := posted[rng.Intn(len(posted))]
			s.run(&op{Op: "post", Advance: advance(), Key: orig.Key, Desc: orig.Desc, Meta: orig.Meta, Postings: orig.Postings})
		case p < 75 && len(posted) > 0: // same key, different request
			orig := posted[rng.Intn(len(posted))]
			k := orig.Key
			if k == "" {
				k = "k-1"
			}
			s.run(&op{Op: "post", Key: k, Desc: orig.Desc + "!", Meta: orig.Meta, Postings: orig.Postings})
		case p < 81: // USD movements, sometimes overdrawing the wallet
			amt := money.New(1+rng.Int63n(60_00), money.USD)
			legs := ps(dr("usd:wallet", amt), cr("usd:cash", amt))
			if rng.Intn(2) == 0 {
				legs = ps(dr("usd:cash", amt), cr("usd:wallet", amt))
			}
			track(s.run(&op{Op: "post", Advance: advance(), Key: key(), Desc: "usd", Postings: legs}))
		case p < 89: // time passes; sweep
			s.run(&op{Op: "expire", Advance: 1 + int64(rng.Intn(90))})
		case p < 91: // a short judicial block: freeze now, lift a few steps later
			if len(frozen) > 0 {
				for _, id := range frozen {
					s.run(&op{Op: "unfreeze", Account: id})
				}
				frozen = nil
			} else {
				id := wallet(rng.Intn(wallets))
				s.run(&op{Op: "freeze", Account: id})
				frozen = append(frozen, id)
			}
		case p < 96: // malformed requests
			from, to := pair()
			var legs []ledger.Posting
			timeout := int64(0)
			switch rng.Intn(6) {
			case 0:
				legs = ps(dr(from, brl(1)))
			case 1:
				legs = ps(dr(from, brl(2)), cr(to, brl(1)))
			case 2:
				legs = ps(dr(from, brl(0)), cr(to, brl(0)))
			case 3:
				legs = ps(dr(from, brl(1)), cr("usd:wallet", brl(1)))
			case 4:
				legs = ps(dr(from, brl(1)), cr("wallet:zz", brl(1)))
			default:
				legs = ps(dr(from, brl(1)), cr(to, brl(1)))
				timeout = 5
			}
			s.run(&op{Op: "post", Key: key(), Postings: legs, Timeout: timeout})
		default: // same account on both sides
			from, _ := pair()
			track(s.run(&op{Op: "post", Key: key(), Desc: "self", Postings: ps(dr(from, brl(7)), cr(from, brl(7)))}))
		}
	}
	for i := 0; i < wallets; i++ {
		s.run(&op{Op: "unfreeze", Account: wallet(i)})
	}
	s.run(&op{Op: "expire", Advance: 600})
}
