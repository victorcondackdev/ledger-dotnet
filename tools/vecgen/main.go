func ledgerErr(err error) string {
	sentinels := []struct {
		err  error
		name string
	}{
		{ledger.ErrAccountNotFound, "AccountNotFound"},
		{ledger.ErrAccountExists, "AccountExists"},
		{ledger.ErrInvalidAccount, "InvalidAccount"},
		{ledger.ErrTxNotFound, "TransactionNotFound"},
		{ledger.ErrInvalidPostings, "InvalidPostings"},
		{ledger.ErrUnbalanced, "Unbalanced"},
		{ledger.ErrCurrencyMismatch, "CurrencyMismatch"},
		{ledger.ErrAccountFrozen, "AccountFrozen"},
		{ledger.ErrInsufficientFunds, "InsufficientFunds"},
		{ledger.ErrOverflow, "Overflow"},
		{ledger.ErrIdempotencyConflict, "IdempotencyConflict"},
		{ledger.ErrDuplicateIdempotencyKey, "DuplicateIdempotencyKey"},
		{ledger.ErrNotPending, "NotPending"},
		{ledger.ErrPendingExpired, "PendingExpired"},
		{ledger.ErrExceedsPending, "ExceedsPending"},
		{ledger.ErrNotReversible, "NotReversible"},
		{ledger.ErrAlreadyReversed, "AlreadyReversed"},
	}
	for _, s := range sentinels {
		if errors.Is(err, s.err) {
			return s.name
		}
	}
	panic(fmt.Sprintf("unexpected ledger error %v", err))
}

type clock struct{ t time.Time }

func (c *clock) Now() time.Time { return c.t }

var scenarioStart = time.Date(2026, 11, 2, 9, 0, 0, 0, time.UTC)

// op is one scenario step; it is executed in Go and emitted for C#.
type op struct {
	Op        string
	Advance   int64 // seconds the clock moves before the step
	Open      *ledger.Account
	Account   ledger.AccountID // freeze / unfreeze
	Key       string
	Desc      string
	Meta      []string // alternating keys and values, no duplicate keys
	Postings  []ledger.Posting
	Timeout   int64 // seconds
	Ref       ledger.TxID
	Amount    int64
	AmountCur money.Currency // "" means no amount
	Expect    string
}

func (o *op) meta() map[string]string {
	if len(o.Meta) == 0 {
		return nil
	}
	m := map[string]string{}
	for i := 0; i+1 < len(o.Meta); i += 2 {
		m[o.Meta[i]] = o.Meta[i+1]
	}
	return m
}

func (o *op) amount() *money.Amount {
	if o.AmountCur == "" {
		return nil
	}
	a := money.New(o.Amount, o.AmountCur)
	return &a
}

type scenario struct {
	l   *ledger.Ledger
	clk *clock
	ops []*op
}

func newScenario() *scenario {
	s := &scenario{clk: &clock{t: scenarioStart}}
	n := 0
	s.l = ledger.New(memstore.New(),
		ledger.WithClock(s.clk.Now),
		ledger.WithIDGenerator(func() ledger.TxID { n++; return ledger.TxID(fmt.Sprintf("tx-%03d", n)) }))
	return s
}

func txResult(tx ledger.Transaction, err error) string {
	if err != nil {
		return "error " + ledgerErr(err)
	}
	return fmt.Sprintf("%s seq=%d %x", tx.ID, tx.Seq, tx.Hash)
}

func okResult(err error) string {
	if err != nil {
		return "error " + ledgerErr(err)
	}
	return "ok"
}

// run executes o and records it; it returns the transaction ID on success.
func (s *scenario) run(o *op) ledger.TxID {
	s.clk.t = s.clk.t.Add(time.Duration(o.Advance) * time.Second)
	l := s.l
	req := ledger.Request{IdempotencyKey: o.Key, Description: o.Desc, Metadata: o.meta(), Postings: o.Postings,
		Timeout: time.Duration(o.Timeout) * time.Second}
	res := ledger.ResolveRequest{ID: o.Ref, IdempotencyKey: o.Key, Description: o.Desc, Metadata: o.meta(), Amount: o.amount()}
	switch o.Op {
	case "open":
		_, err := l.OpenAccount(ctx, *o.Open)
		o.Expect = okResult(err)
	case "post":
		o.Expect = txResult(l.Post(ctx, req))
	case "hold":
		o.Expect = txResult(l.Hold(ctx, req))
	case "post_pending":
		o.Expect = txResult(l.PostPending(ctx, res))
	case "void_pending":
		o.Expect = txResult(l.VoidPending(ctx, res))
	case "reverse":
		o.Expect = txResult(l.Reverse(ctx, res))
	case "expire":
		n, err := l.ExpirePending(ctx)
		if err != nil {
			o.Expect = "error " + ledgerErr(err)
		} else {
			o.Expect = fmt.Sprintf("expired %d", n)
		}
	case "freeze":
		o.Expect = okResult(l.Freeze(ctx, o.Account))
	case "unfreeze":
		o.Expect = okResult(l.Unfreeze(ctx, o.Account))
	default:
		panic(o.Op)
	}
	s.ops = append(s.ops, o)
	if strings.HasPrefix(o.Expect, "tx-") {
		return ledger.TxID(strings.Fields(o.Expect)[0])
	}
	return ""
}

func brl(minor int64) money.Amount { return money.New(minor, money.BRL) }

func dr(id ledger.AccountID, a money.Amount) ledger.Posting {
	return ledger.Posting{Account: id, Direction: ledger.Debit, Amount: a}
}

func cr(id ledger.AccountID, a money.Amount) ledger.Posting {
	return ledger.Posting{Account: id, Direction: ledger.Credit, Amount: a}
}

func ps(p ...ledger.Posting) []ledger.Posting { return p }

func (s *scenario) open(a ledger.Account) { s.run(&op{Op: "open", Open: &a}) }

// genScenario runs a scenario, emits its tables and returns the C#
// expression that builds its ScenarioVectors.
func genScenario(w *writer, name string, build func(*scenario)) string {
	s := newScenario()
	build(s)
	l := s.l

	var opRows [][]string
	for _, o := range s.ops {
		open := "null"
		if a := o.Open; a != nil {
			normal := ""
			if a.Normal != 0 {
				normal = a.Normal.String()
			}
			open = fmt.Sprintf("new ScenarioAccount(%s, %s, %s, %s, %s, %s, %s)", lit(string(a.ID)), lit(a.Code), lit(a.Name),
				lit(string(a.Currency)), lit(a.Type.String()), lit(normal), lit(a.Flags.String()))
		}
		var postings []string
		for _, p := range o.Postings {
			postings = append(postings, fmt.Sprintf("new(%s, %s, %s, %s)", lit(string(p.Account)), lit(p.Direction.String()),
				num(p.Amount.Minor()), lit(string(p.Amount.Currency()))))
		}
		meta := o.Meta
		if meta == nil {
			meta = []string{}
		}
		opRows = append(opRows, []string{lit(o.Op), num(o.Advance), open, lit(string(o.Account)), lit(o.Key), lit(o.Desc),
			strs(meta), "new ScenarioPosting[] { " + strings.Join(postings, ", ") + " }", num(o.Timeout), lit(string(o.Ref)),
			num(o.Amount), lit(string(o.AmountCur)), lit(o.Expect)})
	}
	w.table(name+"Ops", "ScenarioOp", opRows)

	var txRows [][]string
	var times []time.Time
	for after := uint64(0); ; {
		page, err := l.Transactions(ctx, after, 1000)
		if err != nil {
			panic(err)
		}
		for _, t := range page {
			exp := int64(0)
			if !t.ExpiresAt.IsZero() {
				exp = t.ExpiresAt.Unix()
			}
			var legs []string
			for _, p := range t.Postings {
				legs = append(legs, p.Direction.String()+" "+string(p.Account)+" "+p.Amount.String())
			}
			txRows = append(txRows, []string{num(int64(t.Seq)), lit(string(t.ID)), lit(t.Kind.String()), lit(string(t.Ref)),
				lit(t.IdempotencyKey), num(t.Timestamp.Unix()), num(exp), lit(t.Description), lit(strings.Join(legs, "; ")),
				lit(fmt.Sprintf("%x", t.RequestHash)), lit(fmt.Sprintf("%x", t.PrevHash)), lit(fmt.Sprintf("%x", t.Hash))})
			times = append(times, t.Timestamp)
			after = t.Seq
		}
		if len(page) < 1000 {
			break
		}
	}
	w.table(name+"Transactions", "ScenarioTx", txRows)

	accs, err := l.Accounts(ctx)
	if err != nil {
		panic(err)
	}
	var lineRows, pageRows [][]string
	for _, a := range accs {
		for _, holds := range []bool{true, false} {
			opt := ledger.StatementOptions{Limit: 3, IncludeHolds: holds}
			if holds {
				opt.Limit = 4
			}
			for pageNo := 1; ; pageNo++ {
				st, err := l.Statement(ctx, a.ID, opt)
				if err != nil {
					panic(err)
				}
				for _, ln := range st.Lines {
					lineRows = append(lineRows, []string{lit(string(a.ID)), boolLit(holds), strconv.Itoa(pageNo), num(int64(ln.Seq)),
						lit(string(ln.TxID)), lit(ln.Kind.String()), num(ln.Time.Unix()), lit(ln.Description),
						lit(ln.Direction.String()), lit(ln.Phase.String()), num(ln.Amount.Minor()), num(ln.Balance.Minor()),
						num(ln.Available.Minor())})
				}
				pageRows = append(pageRows, []string{lit(string(a.ID)), boolLit(holds), strconv.Itoa(pageNo),
					strconv.Itoa(len(st.Lines)), lit(st.NextCursor)})
				if st.NextCursor == "" {
					break
				}
				opt.Cursor = st.NextCursor
			}
		}
	}
	w.table(name+"Lines", "ScenarioLine", lineRows)
	w.table(name+"Pages", "ScenarioPage", pageRows)

	tb, err := l.TrialBalance(ctx)
	if err != nil {
		panic(err)
	}
	if err := tb.Check(); err != nil {
		panic(err)
	}
	var tbRows [][]string
	for _, r := range tb.Rows {
		tbRows = append(tbRows, []string{lit(string(r.Account.ID)), lit(string(r.Account.Currency)), num(r.DebitsPosted.Minor()),
			num(r.CreditsPosted.Minor()), num(r.DebitsPending.Minor()), num(r.CreditsPending.Minor()), num(r.Balance.Minor())})
	}
	w.table(name+"TrialBalance", "ScenarioTrialRow", tbRows)

	probes := []time.Time{scenarioStart.Add(-time.Second), scenarioStart}
	for i := 0; i < len(times); i += 1 + len(times)/10 {
		probes = append(probes, times[i], times[i].Add(-time.Second))
	}
	if len(times) > 0 {
		probes = append(probes, times[len(times)-1], times[len(times)-1].Add(time.Hour))
	}
	var atRows [][]string
	for _, a := range accs {
		for _, p := range probes {
			b, err := l.BalanceAt(ctx, a.ID, p)
			if err != nil {
				panic(err)
			}
			atRows = append(atRows, []string{lit(string(a.ID)), num(p.Unix()), num(b.Posted.Minor()), num(b.Pending.Minor()),
				num(b.Available.Minor())})
		}
	}
	w.table(name+"BalancesAt", "ScenarioBalanceAt", atRows)

	head, err := l.VerifyChain(ctx)
	if err != nil {
		panic(err)
	}
	if err := l.VerifyBalances(ctx); err != nil {
		panic(err)
	}
	return fmt.Sprintf("new ScenarioVectors(%s, %s, %sOps, %sTransactions, %sLines, %sPages, %sTrialBalance, %sBalancesAt, %s, %s)",
		lit(name), num(scenarioStart.Unix()), name, name, name, name, name, name, num(int64(head.Seq)), lit(fmt.Sprintf("%x", head.Hash)))
}

