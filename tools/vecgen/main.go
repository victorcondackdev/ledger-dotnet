var rng = rand.New(rand.NewSource(20261121))

var ctx = context.Background()

// lit renders s as a C# string literal. Non-ASCII and control characters
// are written as \u escapes so the generated file is pure ASCII.
func lit(s string) string {
	if !utf8.ValidString(s) {
		panic(fmt.Sprintf("invalid UTF-8 in vector: %q", s))
	}
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch {
		case r == '"':
			b.WriteString(`\"`)
		case r == '\\':
			b.WriteString(`\\`)
		case r >= 0x20 && r < 0x7F:
			b.WriteRune(r)
		default:
			for _, u := range utf16.Encode([]rune{r}) {
				fmt.Fprintf(&b, `\u%04X`, u)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}

// num renders an int64 as a C# long literal.
func num(v int64) string {
	if v == math.MinInt64 {
		return "long.MinValue"
	}
	return strconv.FormatInt(v, 10)
}

func longs(vs []int64) string {
	parts := make([]string, len(vs))
	for i, v := range vs {
		parts[i] = num(v)
	}
	return "new long[] { " + strings.Join(parts, ", ") + " }"
}

func strs(vs []string) string {
	parts := make([]string, len(vs))
	for i, v := range vs {
		parts[i] = lit(v)
	}
	return "new string[] { " + strings.Join(parts, ", ") + " }"
}

func boolLit(b bool) string {
	if b {
		return "true"
	}
	return "false"
}

type writer struct{ b bytes.Buffer }

func (w *writer) f(format string, args ...any) { fmt.Fprintf(&w.b, format, args...) }

func (w *writer) table(name, elemType string, rows [][]string) {
	w.f("\n    public static readonly %s[] %s =\n    {\n", elemType, name)
	for _, r := range rows {
		if strings.HasPrefix(elemType, "(") {
			w.f("        (%s),\n", strings.Join(r, ", "))
		} else {
			w.f("        new(%s),\n", strings.Join(r, ", "))
		}
	}
	w.f("    };\n")
}

func main() {
	w := &writer{}
	w.f("// <auto-generated>\n")
	w.f("// Generated by tools/vecgen from the Go implementation (github.com/victorcondackdev/ledger-go).\n")
	w.f("// Do not edit by hand; regenerate with: go -C tools/vecgen run . > tests/Ledger.Tests/Parity/GoVectors.g.cs\n")
	w.f("// </auto-generated>\n\n")
	w.f("namespace Ledger.Tests.Parity;\n\n")
	w.f("internal static class GoVectors\n{")

	genCurrencies(w)
	genParse(w)
	genFormat(w)
	genParseLocale(w)
	genAllocate(w)
	scripted := genScenario(w, "Scripted", scriptedScenario)
	random := genScenario(w, "Random", randomScenario)

	w.f("\n    public static readonly ScenarioVectors[] Scenarios = { %s, %s };\n", scripted, random)
	w.f("}\n")
	if _, err := os.Stdout.Write(w.b.Bytes()); err != nil {
		panic(err)
	}
}

