// Command vecgen generates the cross-language parity vectors used by the C#
// test suite. It runs the Go implementation
// (github.com/victorcondackdev/ledger-go) over a deterministic corpus and
// writes the observed outputs as C# literals: money parsing, formatting and
// allocation tables, and complete ledger scenarios (every operation with its
// outcome, every sealed transaction with its hashes, statements with
// cursors, trial balances, point-in-time balances and the chain head).
//
// Usage, from the repository root, with the Go module cloned next to it:
//
//	go -C tools/vecgen run . > tests/Ledger.Tests/Parity/GoVectors.g.cs
